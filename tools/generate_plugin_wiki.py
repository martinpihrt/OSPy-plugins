WIKI_LINK_RE = re.compile(r"(?<!!)\[[^]]+\]\(([^)]+)\)")


def validate_pages(pages: dict[str, str], plugin_count: int) -> None:
    plugin_pages = [name for name in pages if name.startswith("Plugin-") and name != "Plugin-Catalog.md"]
    if len(plugin_pages) != plugin_count:
        raise ValueError(f"Expected {plugin_count} plug-in pages, generated {len(plugin_pages)}")
    page_stems = {Path(name).stem for name in pages}
    for name, content in pages.items():
        if not content.startswith(GENERATED_MARKER):
            raise ValueError(f"{name}: missing generated marker")
        if "$def with" in content or "plugin_url(" in content:
            raise ValueError(f"{name}: unresolved template expression")
        for target in WIKI_LINK_RE.findall(content):
            if target.startswith(("http://", "https://", "#", "mailto:")):
                continue
            stem = target.split("#", 1)[0].removesuffix(".md")
            if stem and stem not in page_stems:
                raise ValueError(f"{name}: unresolved internal Wiki link {target!r}")


def write_or_check(output: Path, pages: dict[str, str], check: bool) -> int:
    output.mkdir(parents=True, exist_ok=True)
    stale = sorted(
        path.name
        for path in output.glob("Plugin-*.md")
        if path.name not in pages and GENERATED_MARKER in path.read_text(encoding="utf-8")
    )
    mismatches: list[str] = []
    for name, expected in pages.items():
        path = output / name
        expected = expected.replace("\r\n", "\n")
        if not expected.endswith("\n"):
            expected += "\n"
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != expected:
            mismatches.append(name)
            if not check:
                path.write_text(expected, encoding="utf-8", newline="\n")
    if not check:
        for name in stale:
            (output / name).unlink()
    if check and (mismatches or stale):
        if mismatches:
            print("Out-of-date or missing Wiki pages: " + ", ".join(mismatches))
        if stale:
            print("Stale generated Wiki pages: " + ", ".join(stale))
        return 1
    action = "verified" if check else "generated"
    print(f"Wiki {action}: {len(pages)} Markdown files, including {len([name for name in pages if name.startswith('Plugin-') and name != 'Plugin-Catalog.md'])} plug-in pages.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="path to the OSPy-plugins.wiki checkout")
    parser.add_argument("--check", action="store_true", help="fail if generated Wiki files differ")
    args = parser.parse_args()
    try:
        plugins = load_plugins()
        pages = render_pages(plugins)
        validate_pages(pages, len(plugins))
        return write_or_check(args.output.resolve(), pages, args.check)
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"Wiki generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
