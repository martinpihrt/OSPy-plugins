def wiki_page(plugin_id: str) -> str:
    return "Plugin-" + plugin_id.replace("_", "-")


def clean_text(value: object, field: str, manifest: Path) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{manifest}: missing non-empty {field!r}")
    return " ".join(value.split())


def load_plugins() -> list[dict[str, object]]:
    plugins: list[dict[str, object]] = []
    for manifest in sorted(PLUGINS_DIR.glob("*/plugin.json")):
        data = json.loads(manifest.read_text(encoding="utf-8"))
        plugin_id = manifest.parent.name
        declared_id = data.get("id", plugin_id)
        if declared_id != plugin_id:
            raise ValueError(f"{manifest}: id must match directory name {plugin_id!r}")
        readme = manifest.parent / "README.md"
        if not readme.is_file():
            raise ValueError(f"{manifest.parent}: missing README.md")
        help_files = sorted(manifest.parent.glob("templates/*help*.html"))
        plugins.append(
            {
                "id": plugin_id,
                "name": clean_text(data.get("name"), "name", manifest),
                "version": clean_text(data.get("version"), "version", manifest),
                "description": clean_text(
                    data.get("description"), "description", manifest
                ),
                "manifest": data,
                "manifest_path": manifest,
                "readme": readme,
                "help": help_files[0] if help_files else None,
            }
        )

    if not plugins:
        raise ValueError(f"No plug-in manifests found under {PLUGINS_DIR}")

    known = {str(plugin["id"]) for plugin in plugins}
    categorized = {plugin_id for ids in CATEGORIES.values() for plugin_id in ids}
    missing = sorted(known - categorized)
    stale = sorted(categorized - known)
    if missing or stale:
        raise ValueError(
            f"Category mapping mismatch; uncategorized={missing}, missing manifests={stale}"
        )
    return sorted(plugins, key=lambda item: str(item["name"]).casefold())


def category_for(plugin_id: str) -> str:
    for category, ids in CATEGORIES.items():
        if plugin_id in ids:
            return category
    raise ValueError(f"No category for {plugin_id}")


def markdown_cell(value: object) -> str:
    return str(value).replace("|", r"\|").replace("\n", " ")


def display_list(values: object) -> str:
    if not values:
        return "None"
    if not isinstance(values, list):
        values = [values]
    return ", ".join(f"`{markdown_cell(value)}`" for value in values)


def version_minimum(section: object) -> str:
    if not isinstance(section, dict):
        return "Not specified"
    value = section.get("min") or section.get("min_version")
    return f"`{value}` or newer" if value else "Not specified"


def dependency_list(plugin: dict[str, object], by_id: dict[str, dict[str, object]]) -> str:
    dependencies = plugin["manifest"].get("dependencies", [])
    if not dependencies:
        return "None"
    rendered: list[str] = []
    for dependency in dependencies:
        if isinstance(dependency, str):
            dependency_id = dependency
            required = True
        else:
            dependency_id = str(dependency.get("id", ""))
            required = bool(dependency.get("required", True))
        target = by_id.get(dependency_id)
        label = str(target["name"]) if target else dependency_id
        link = f"[{label}]({wiki_page(dependency_id)})" if target else f"`{label}`"
        rendered.append(f"{link} ({'required' if required else 'optional'})")
    return ", ".join(rendered)


def requirements_list(manifest: dict[str, object]) -> str:
    requirements = manifest.get("requirements", [])
    if not requirements:
        return "None"
    rendered: list[str] = []
    for requirement in requirements:
        if isinstance(requirement, str):
            rendered.append(f"`{requirement}`")
            continue
        module = requirement.get("module")
        package = requirement.get("package")
        label = module or package or "unnamed"
        detail = f" / `{package}`" if package and package != module else ""
        required = "required" if requirement.get("required", True) else "optional"
        rendered.append(f"`{label}`{detail} ({required})")
    return ", ".join(rendered)


def hardware_summary(manifest: dict[str, object]) -> str:
    hardware = manifest.get("hardware")
    if not isinstance(hardware, dict) or not hardware:
        return "No dedicated hardware requirement declared"
    parts: list[str] = []
    if hardware.get("platforms"):
        parts.append(f"platforms: {display_list(hardware['platforms'])}")
    if hardware.get("requires"):
        parts.append(f"interfaces: {display_list(hardware['requires'])}")
    if hardware.get("i2c"):
        addresses: list[str] = []
        entries = hardware["i2c"]
        if not isinstance(entries, list):
            entries = [entries]
        for entry in entries:
            if isinstance(entry, dict) and entry.get("alternatives"):
                addresses.append(" or ".join(f"`{item}`" for item in entry["alternatives"]))
            else:
                addresses.append(f"`{entry}`")
        parts.append("I²C: " + ", ".join(addresses))
    return "; ".join(parts) if parts else "Declared in the manifest"


def integration_summary(manifest: dict[str, object]) -> str:
    parts: list[str] = []
    provider = manifest.get("provider")
    if isinstance(provider, dict) and provider.get("contract"):
        parts.append(f"provider `{provider['contract']}`")
    mobile = manifest.get("mobile")
    if isinstance(mobile, dict) and mobile.get("api_version"):
        parts.append(f"Mobile API v{mobile['api_version']}")
    return ", ".join(parts) if parts else "No provider or mobile API declared"


def _rewrite_asset_urls(text: str, plugin_id: str) -> str:
    raw_base = f"https://raw.githubusercontent.com/martinpihrt/OSPy-plugins/master/plugins/{plugin_id}/"
    blob_base = f"{REPOSITORY_URL}/blob/master/plugins/{plugin_id}/"
    text = re.sub(
        rf'(?P<prefix>src=["\'])/plugins/{re.escape(plugin_id)}/(?P<path>[^"\']+)',
        lambda match: match.group("prefix") + raw_base + match.group("path"),
        text,
    )
    text = re.sub(
        rf'(?P<prefix>href=["\'])/plugins/{re.escape(plugin_id)}/(?P<path>[^"\']+)',
        lambda match: match.group("prefix") + blob_base + match.group("path"),
        text,
    )
    return text


def _is_structural(line: str) -> bool:
    stripped = line.lstrip()
    return bool(
        not stripped
        or stripped.startswith(("#", "- ", "* ", "+ ", ">", "```", "~~~", "|", "<", "<!--"))
        or re.match(r"\d+[.)]\s", stripped)
        or re.match(r"^\[[^]]+\]:", stripped)
    )


def _join_plain_paragraphs(lines: list[str]) -> list[str]:
    output: list[str] = []
    buffer: list[str] = []
    in_fence = False

    def flush() -> None:
        if buffer:
            output.append(" ".join(part.strip() for part in buffer))
            buffer.clear()

    for line in lines:
        if line.lstrip().startswith(("```", "~~~")):
            flush()
            in_fence = not in_fence
            output.append(line.rstrip())
        elif in_fence:
            output.append(line.rstrip())
        elif not line.strip():
            flush()
            if output and output[-1] != "":
                output.append("")
        elif _is_structural(line):
            flush()
            output.append(line.rstrip())
        else:
            buffer.append(line)
    flush()
    while output and output[-1] == "":
        output.pop()
    return output


def readme_body(plugin: dict[str, object]) -> str:
    lines = plugin["readme"].read_text(encoding="utf-8").replace("\r\n", "\n").splitlines()
    if len(lines) >= 2 and re.fullmatch(r"=+", lines[1].strip()):
        lines = lines[2:]
    elif lines and re.match(r"^#\s+", lines[0]):
        lines = lines[1:]
    while lines and not lines[0].strip():
        lines.pop(0)

    converted: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index].rstrip()
        if index + 1 < len(lines) and re.fullmatch(r"[-=]{3,}", lines[index + 1].strip()):
            converted.append(f"### {line.strip()}")
            index += 2
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            depth = min(len(heading.group(1)) + 2, 6)
            converted.append("#" * depth + " " + heading.group(2).strip())
        else:
            converted.append(line)
        index += 1

    body = "\n".join(_join_plain_paragraphs(converted))
    return _rewrite_asset_urls(body, str(plugin["id"])).strip()


TRANSLATION_PATTERNS = (
    re.compile(r"\$_\((?:u)?'((?:\\.|[^'\\])*)'\)"),
    re.compile(r'\$_\((?:u)?"((?:\\.|[^"\\])*)"\)'),
)


def _translated_strings(line: str) -> list[str]:
    found: list[tuple[int, str]] = []
    for pattern, quote in ((TRANSLATION_PATTERNS[0], "'"), (TRANSLATION_PATTERNS[1], '"')):
        for match in pattern.finditer(line):
            try:
                value = ast.literal_eval(quote + match.group(1) + quote)
            except (SyntaxError, ValueError):
                value = match.group(1)
            found.append((match.start(), html.unescape(str(value)).strip()))
    return [value for _, value in sorted(found) if value]


def help_body(plugin: dict[str, object]) -> str:
    help_path = plugin["help"]
    if help_path is None:
        return ""
    source = help_path.read_text(encoding="utf-8").replace("\r\n", "\n")
    blocks: list[str] = []
    seen: set[str] = set()
    for source_line in source.splitlines():
        line = source_line.strip()
        if not line or line.startswith(("$def", "$var", "<link")):
            continue
        if "plugin_url(" in line or "id=\"controls\"" in line:
            continue
        values = _translated_strings(line)
        if not values:
            continue
        text = " ".join(values)
        if not text or text in seen:
            continue
        lowered = text.casefold()
        if lowered.endswith(" - help") or lowered in {"cancel", "back", "overview", "settings"}:
            continue
        seen.add(text)
        if re.search(r"<h[1-6]|<div class=[\"']title", line, re.IGNORECASE):
            blocks.append(f"### {text}")
        elif "<li" in line.lower():
            blocks.append(f"- {text}")
        else:
            blocks.append(text)

    plugin_id = str(plugin["id"])
    raw_base = f"https://raw.githubusercontent.com/martinpihrt/OSPy-plugins/master/plugins/{plugin_id}/"
    blob_base = f"{REPOSITORY_URL}/blob/master/plugins/{plugin_id}/"
    image_paths: list[str] = []
    for match in re.finditer(r'<img[^>]+src=["\']([^"\']+)["\']', source, re.IGNORECASE):
        image_path = match.group(1)
        prefix = f"/plugins/{plugin_id}/"
        if image_path.startswith(prefix):
            image_path = image_path[len(prefix) :]
        if image_path.startswith(("http://", "https://")):
            raw_url = image_path
            blob_url = image_path
        else:
            raw_url = raw_base + image_path.lstrip("/")
            blob_url = blob_base + image_path.lstrip("/")
        rendered = f"[![{Path(image_path).stem.replace('_', ' ')}]({raw_url})]({blob_url})"
        if rendered not in image_paths:
            image_paths.append(rendered)

    related_links: list[str] = []
    for match in re.finditer(
        r'<a[^>]+href=["\'](https?://[^"\']+)["\'][^>]*>(.*?)</a>',
        source,
        re.IGNORECASE | re.DOTALL,
    ):
        url = html.unescape(match.group(1))
        label_values = _translated_strings(match.group(2))
        label = " ".join(label_values)
        if not label:
            label = html.unescape(re.sub(r"<[^>]+>", "", match.group(2))).strip()
        rendered = f"- [{label or url}]({url})"
        if rendered not in related_links:
            related_links.append(rendered)

    if related_links or image_paths:
        blocks.append("### Related links and diagrams")
        if related_links:
            blocks.append("\n".join(related_links))
        blocks.extend(image_paths)
    return "\n\n".join(blocks)


def render_plugin_page(plugin: dict[str, object], by_id: dict[str, dict[str, object]]) -> str:
    manifest = plugin["manifest"]
    plugin_id = str(plugin["id"])
    permissions = display_list(manifest.get("permissions", []))
    author = manifest.get("author") or "Not specified"
    source = f"{REPOSITORY_URL}/tree/master/plugins/{plugin_id}"
    lines = [
        GENERATED_MARKER,
        "",
        f"# {plugin['name']}",
        "",
        f"> {plugin['description']}",
        "",
        "## At a glance",
        "",
        "| Item | Value |",
        "| --- | --- |",
        f"| Version | `{plugin['version']}` |",
        f"| Category | [{category_for(plugin_id)}](Plugin-Catalog#{category_for(plugin_id).lower().replace(' ', '-').replace(',', '').replace('²', '2')}) |",
        f"| Author | {markdown_cell(author)} |",
        f"| License | `{manifest.get('license', 'Not specified')}` |",
        f"| OSPy | {version_minimum(manifest.get('ospy'))} |",
        f"| Python | {version_minimum(manifest.get('python'))} |",
        f"| Permissions | {permissions} |",
        f"| Hardware | {hardware_summary(manifest)} |",
        f"| Dependencies | {dependency_list(plugin, by_id)} |",
        f"| Python/OS packages | {requirements_list(manifest)} |",
        f"| Interfaces | {integration_summary(manifest)} |",
        f"| Source | [Open the plug-in directory]({source}) |",
        "",
        "## What it is for",
        "",
        str(plugin["description"]),
        "",
        "## How it works and how to configure it",
        "",
        readme_body(plugin),
    ]
    extracted_help = help_body(plugin)
    if extracted_help:
        lines.extend(
            [
                "",
                "## In-app help and settings notes",
                "",
                "The following notes are generated from the help page shipped with this plug-in. Field names are also explained directly in the OSPy settings page.",
                "",
                extracted_help,
            ]
        )
    lines.extend(
        [
            "",
            "## Support",
            "",
            "Check **OSPy → Diagnostics** first and remove passwords, tokens, private addresses and other secrets before sharing logs. Report reproducible plug-in problems in the [OSPy-plugins issue tracker](https://github.com/martinpihrt/OSPy-plugins/issues).",
            "",
            "[Back to the plug-in catalog](Plugin-Catalog)",
            "",
        ]
    )
    return "\n".join(lines)


def render_catalog(plugins: list[dict[str, object]]) -> str:
    by_id = {str(plugin["id"]): plugin for plugin in plugins}
    lines = [
        GENERATED_MARKER,
        "",
        "# Plug-in catalog",
        "",
        f"This catalog contains all {len(plugins)} official OSPy plug-ins. Select a name for its purpose, operation, requirements, settings and troubleshooting information.",
    ]
    for category, ids in CATEGORIES.items():
        lines.extend(
            [
                "",
                f"## {category}",
                "",
                "| Plug-in | Version | What it does |",
                "| --- | --- | --- |",
            ]
        )
        selected = sorted((by_id[plugin_id] for plugin_id in ids), key=lambda item: str(item["name"]).casefold())
        for plugin in selected:
            lines.append(
                f"| [{markdown_cell(plugin['name'])}]({wiki_page(str(plugin['id']))}) | `{plugin['version']}` | {markdown_cell(plugin['description'])} |"
            )
    lines.extend(["", "[Back to the documentation home](Home)", ""])
    return "\n".join(lines)


